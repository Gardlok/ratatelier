#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn art_export_contains_painted_glyph() {
        let mut project = Project::new("logo", 3, 2);
        project.canvas_mut().set_cell(
            crate::model::Point::new(1, 0),
            Cell::painted('X', CellStyle::default()),
        );
        let source = export_art(&project);
        assert!(source.contains("\\\"X\\\"") || source.contains("\"X\""));
        assert!(source.contains("impl Widget"));
    }

    #[test]
    fn animation_export_preserves_style_and_duration() {
        let mut project = Project::new("blink", 2, 1);
        project.frame_mut().duration_ms = 350;
        project.canvas_mut().set_cell(
            crate::model::Point::new(0, 0),
            Cell::painted(
                'X',
                CellStyle {
                    fg: ColorSpec::LightCyan,
                    bold: true,
                    ..CellStyle::default()
                },
            ),
        );
        let source = export_animation(&project);
        assert!(source.contains("350"));
        assert!(source.contains("Color::LightCyan"));
        assert!(source.contains("Modifier::BOLD"));
    }

    #[test]
    fn ansi_export_contains_style_and_reset_sequences() {
        let mut project = Project::new("ansi", 1, 1);
        project.canvas_mut().set_cell(
            crate::model::Point::new(0, 0),
            Cell::painted(
                'X',
                CellStyle {
                    fg: ColorSpec::LightGreen,
                    underlined: true,
                    ..CellStyle::default()
                },
            ),
        );
        let output = export_ansi(&project);
        assert!(output.contains("\x1b[0;92;49;4mX\x1b[0m"));
    }

    #[test]
    fn component_export_uses_all_widget_states() {
        let project = Project::new("component", 2, 1);
        let source = export_component(&project);
        assert!(source.contains("ComponentState::Focused"));
        assert!(source.contains("ComponentState::Disabled"));
    }

    #[test]
    fn sparkline_parser_has_fallback() {
        assert!(!parse_sparkline("nonsense").is_empty());
        assert_eq!(parse_sparkline("1, 2, 3"), vec![1, 2, 3]);
    }
}
