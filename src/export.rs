#[cfg(test)]
mod tests {
    use std::{
        fs,
        process::Command,
        sync::atomic::{AtomicUsize, Ordering},
    };

    use super::*;

    static RUSTFMT_FIXTURE: AtomicUsize = AtomicUsize::new(0);

    fn assert_rustfmt_clean(label: &str, source: &str) {
        let nonce = RUSTFMT_FIXTURE.fetch_add(1, Ordering::Relaxed);
        let path = std::env::temp_dir().join(format!(
            "ratatelier-{label}-{}-{nonce}.rs",
            std::process::id()
        ));
        fs::write(&path, source).expect("generated source fixture should write");

        let mut version_command = Command::new("rustfmt");
        version_command.arg("--version");
        let availability = match version_command.output() {
            Ok(output) => output,
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
                let _ = fs::remove_file(&path);
                return;
            }
            Err(error) => {
                let _ = fs::remove_file(&path);
                panic!("failed to check rustfmt for {label}: {error}");
            }
        };
        if !availability.status.success() {
            let stderr = String::from_utf8_lossy(&availability.stderr);
            if stderr.contains("not installed for the toolchain") {
                let _ = fs::remove_file(&path);
                return;
            }
            let _ = fs::remove_file(&path);
            panic!("rustfmt availability check failed for {label}: {stderr}");
        }

        let mut check_command = Command::new("rustfmt");
        check_command.arg("--check");
        check_command.arg(&path);
        let status = check_command
            .status()
            .expect("rustfmt availability was already verified");
        let _ = fs::remove_file(&path);
        assert!(status.success(), "{label} export was not rustfmt-clean");
    }

    #[test]
    fn art_export_contains_painted_glyph() {
        let mut project = Project::new("logo", 3, 2);
        project.canvas_mut().set_cell(
            crate::model::Point::new(1, 0),
            Cell::painted('X', CellStyle::default()),
        );
        let source = export_art(&project);
        assert!(source.contains("\\\"X\\\"") || source.contains("\"X\""));
        assert!(source.contains("impl Widget"));
        assert_rustfmt_clean("art", &source);
    }

    #[test]
    fn animation_export_preserves_style_and_duration() {
        let mut project = Project::new("blink", 2, 1);
        project.frame_mut().duration_ms = 350;
        project.canvas_mut().set_cell(
            crate::model::Point::new(0, 0),
            Cell::painted(
                'X',
                CellStyle {
                    fg: ColorSpec::LightCyan,
                    bold: true,
                    ..CellStyle::default()
                },
            ),
        );
        let source = export_animation(&project);
        assert!(source.contains("350"));
        assert!(source.contains("Color::LightCyan"));
        assert!(source.contains("Modifier::BOLD"));
        assert_rustfmt_clean("animation", &source);
    }

    #[test]
    fn ansi_export_contains_style_and_reset_sequences() {
        let mut project = Project::new("ansi", 1, 1);
        project.canvas_mut().set_cell(
            crate::model::Point::new(0, 0),
            Cell::painted(
                'X',
                CellStyle {
                    fg: ColorSpec::LightGreen,
                    underlined: true,
                    ..CellStyle::default()
                },
            ),
        );
        let output = export_ansi(&project);
        assert!(output.contains("\x1b[0;92;49;4mX\x1b[0m"));
    }

    #[test]
    fn component_export_uses_all_widget_states() {
        let project = Project::new("component", 2, 1);
        let source = export_component(&project);
        assert!(source.contains("ComponentState::Focused"));
        assert!(source.contains("ComponentState::Disabled"));
        assert_rustfmt_clean("component", &source);
    }

    #[test]
    fn sparkline_parser_has_fallback() {
        assert!(!parse_sparkline("nonsense").is_empty());
        assert_eq!(parse_sparkline("1, 2, 3"), vec![1, 2, 3]);
    }
}
